const listeners = new Set();
let current = "zh";

export function getLang() {
  return current;
}

export function t(key, params = {}) {
  const table = DICTS[current] || ZH;
  let value = table[key] ?? ZH[key] ?? key;
  for (const [name, replacement] of Object.entries(params)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function applyStaticTranslations() {
  for (const element of document.querySelectorAll("[data-i18n]")) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const element of document.querySelectorAll("[data-i18n-html]")) {
    element.innerHTML = t(element.dataset.i18nHtml);
  }
  for (const element of document.querySelectorAll("[data-i18n-placeholder]")) {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  }
  for (const element of document.querySelectorAll("[data-i18n-title]")) {
    element.title = t(element.dataset.i18nTitle);
  }
  for (const element of document.querySelectorAll("[data-i18n-aria]")) {
    element.setAttribute("aria-label", t(element.dataset.i18nAria));
  }
}

export function setLang(lang, persist = true) {
  current = lang === "en" ? "en" : "zh";
  if (persist) localStorage.setItem("p3d.lang", current);
  document.documentElement.lang = current === "en" ? "en" : "zh-CN";
  document.documentElement.dataset.lang = current;
  applyStaticTranslations();
  for (const listener of listeners) {
    try { listener(current); } catch (error) { console.error(error); }
  }
}

export function toggleLang() {
  setLang(current === "zh" ? "en" : "zh");
}

export function onLanguageChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function initI18n() {
  const query = new URLSearchParams(window.location.search).get("lang");
  const stored = localStorage.getItem("p3d.lang");
  current = (query === "en" || query === "zh") ? query : (stored === "en" ? "en" : "zh");
  if (query === "en" || query === "zh") localStorage.setItem("p3d.lang", current);
  document.documentElement.lang = current === "en" ? "en" : "zh-CN";
  document.documentElement.dataset.lang = current;
  applyStaticTranslations();
  return current;
}
